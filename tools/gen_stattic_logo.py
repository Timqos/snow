"""Native-pixel and SVG forms of the user's nine-ribbon circular STATTIC mark."""
from pathlib import Path
from PIL import Image, ImageDraw
ROOT=Path(__file__).resolve().parents[1]
LEFT=(142,92,58,32,0,32,58,92,142)
BEND=(304,304,294,275,260,275,295,310,330)
def main():
    polygons=[]
    for i,(left,bend) in enumerate(zip(LEFT,BEND)):
        y=i*42
        polygons.append(((left,y),(bend-10,y),(bend,y+10),(450,y+10),(450,y+42),(bend+10,y+42),(bend-10,y+22),(left+106,y+22),(left+96,y+11),(left,y+11)))
    paths=''.join('<polygon points="'+' '.join(f'{x},{y}' for x,y in poly)+'"/>' for poly in polygons)
    svg='<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 418 364" fill="#f5f5f1"><title>STATTIC</title><defs><clipPath id="edge"><path d="M0 0H236A182 182 0 0 1 236 364H0Z"/></clipPath></defs><g clip-path="url(#edge)">'+paths+'</g></svg>\n'
    (ROOT/'web/snow/logo.svg').write_text(svg)
    im=Image.new('L',(418*2,364*2));d=ImageDraw.Draw(im)
    for poly in polygons:d.polygon([(x*2,y*2) for x,y in poly],fill=255)
    mask=Image.new('L',im.size);m=ImageDraw.Draw(mask);m.rectangle((0,0,472,728),fill=255);m.ellipse((108,0,836,728),fill=255)
    from PIL import ImageChops
    im=ImageChops.multiply(im,mask).resize((112,98),Image.Resampling.LANCZOS)
    rows=[tuple(sum((im.getpixel((x+b,y))>=128)<<(7-b) for b in range(8)) for x in range(0,112,8)) for y in range(98)]
    out=['/* SPDX-License-Identifier: GPL-3.0-only */','/* User STATTIC brand mark; generated by tools/gen_stattic_logo.py. */','static const uint8_t ST_LOGO[98][14]={']
    out += [' {'+','.join(f'0x{x:02x}' for x in row)+'},' for row in rows]
    out += ['};'];(ROOT/'firmware/src/stattic_logo.h').write_text('\n'.join(out)+'\n')
    (ROOT/'build').mkdir(exist_ok=True)
    im.point(lambda x:255 if x>=128 else 0).save(ROOT/'build/stattic-logo-native.png')
if __name__=='__main__':main()
