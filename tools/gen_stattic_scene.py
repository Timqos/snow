def planet():
    w, h = 22, 15
    g = [["."] * w for _ in range(h)]
    cx, cy, r = 11, 7, 6
    for y in range(h):
        for x in range(w):
            d = math.hypot(x - cx, y - cy)
            if d <= r + 0.3:
                edge = d > r - 0.9
                lit = (x - cx) + (y - cy) < 2
                if edge or (lit and (x + y) % 2 == 0) or (not lit and (x * 3 + y) % 4 == 0):
                    g[y][x] = "X"
    for t in range(0, 360, 4):                            # the ring: a tilted ellipse, the back half behind
        a = math.radians(t)
        x = cx + 10.4 * math.cos(a)
        y = cy + 2.4 * math.sin(a) - 0.35 * 10.4 * math.cos(a) * 0.3
        xi, yi = int(round(x)), int(round(y))
        if 0 <= xi < w and 0 <= yi < h:
            behind = math.sin(a) < 0 and math.hypot(xi - cx, yi - cy) < r
            if not behind:
                g[yi][xi] = "X"
    return "\n".join("".join(r) for r in g)


def moon():
    w = h = 9
    g = [["."] * w for _ in range(h)]
    for y in range(h):
        for x in range(w):
            if math.hypot(x - 4, y - 4) <= 4.2 and math.hypot(x - 6.2, y - 2.8) > 3.6:
                g[y][x] = "X"
    return "\n".join("".join(r) for r in g)


