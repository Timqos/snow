def masks(art):
    rows = [r for r in art.strip("\n").split("\n")]
    w = max(len(r) for r in rows)
    white, accent = [], []
    for r in rows:
        r = r.ljust(w, ".")
        white.append(sum(1 << (w - 1 - i) for i, c in enumerate(r) if c == "X"))
        accent.append(sum(1 << (w - 1 - i) for i, c in enumerate(r) if c == "o"))
    return w, len(rows), white, accent


def main():
    out = Path(sys.argv[1])
    L = ["/* SPDX-License-Identifier: GPL-3.0-only */",
         "/* Generated by tools/gen_stattic_scene.py: HOME 1-3's 1-bit scene sprites (bit w-1-x = column x) */",
         "#ifndef STATTIC_SCENE_H", "#define STATTIC_SCENE_H",
         "typedef struct { uint8_t w, h; const uint32_t *white, *accent; } st_sprite_t;"]
    names = list(S)
    for n in names:
        w, h, wh, ac = masks(S[n])
        assert w <= 32
        L.append("static const uint32_t SC_%s_W[%d]={%s};" % (n, h, ",".join("%du" % v for v in wh)))
        L.append("static const uint32_t SC_%s_A[%d]={%s};" % (n, h, ",".join("%du" % v for v in ac)))
    L.append("enum { %s, SC_COUNT };" % ", ".join("SC_" + n for n in names))
    L.append("static const st_sprite_t SC_SPRITES[SC_COUNT]={")
    for n in names:
        w, h, _, _ = masks(S[n])
        L.append("    {%d,%d,SC_%s_W,SC_%s_A}," % (w, h, n, n))
    L += ["};", "#endif", ""]
    out.write_text("\n".join(L))
    print(len(names), "sprites ->", out)


if __name__ == "__main__":
    main()
