"""Render the forty STATTIC drum presets once, store bounded 22.05k ADPCM shots.
The device only decodes these shots; it does not run four drum synth parts.
"""
import array
import hashlib
import math
from pathlib import Path
import subprocess
import sys
from sampleio import ima_encode

ROOT=Path(__file__).resolve().parents[1]

def main():
    target=Path(sys.argv[1]);out=target.parent
    exe=out/'stattic-drum-render';raw=out/'stattic-drums.raw'
    subprocess.run(['cc','-O2','-w','-I'+str(out),'-I'+str(ROOT/'firmware/src'),
                    str(ROOT/'tests/stattic_engine_vectors.c'),'-lm','-lpthread','-o',str(exe)],check=True)
    subprocess.run([str(exe),str(raw)],check=True,stdout=subprocess.DEVNULL)
    pcm=array.array('h');pcm.frombytes(raw.read_bytes())
    if sys.byteorder!='little':pcm.byteswap()
    assert len(pcm)==40*22050
    # 63-tap Blackman-windowed lowpass before decimation. No extra build dependency.
    taps=[]
    for j in range(-31,32):
        sinc=0.45 if not j else math.sin(math.pi*0.45*j)/(math.pi*j)
        w=0.42+0.5*math.cos(math.pi*j/31)+0.08*math.cos(2*math.pi*j/31)
        taps.append(sinc*w)
    gain=sum(taps);taps=[x/gain for x in taps]
    blob=bytearray();zones=[]
    for sound in range(40):
        x=pcm[sound*22050:(sound+1)*22050]
        y=[sum(x[k+j-31]*c for j,c in enumerate(taps) if 0<=k+j-31<len(x)) for k in range(0,len(x),2)]
        # A tiny end fade prevents a truncated long factory tail from clicking.
        fade=110
        for j in range(fade):y[-fade+j]*=(fade-1-j)/(fade-1)
        pk=max(1,max(abs(v) for v in y));scale=min(2.0,24000/pk)
        shot=[max(-32767,min(32767,round(v*scale))) for v in y]
        data,_=ima_encode(shot,len(shot))
        zones.append((len(blob),len(shot)))
        blob.extend(data)
    h=['/* generated by tools/gen_stattic_drums.py; GPL-3.0-only */','#pragma once',
       '#define SMP_NSETS 1u','#define SMP_SET_NAMES_INIT "STATTIC"',
       'static const uint8_t SMP_DATA[]={']
    for at in range(0,len(blob),24):h.append('    '+','.join(str(x) for x in blob[at:at+24])+',')
    h+=['};','static const smp_zone_t SMP_ZONES[]={']
    for i,(off,n) in enumerate(zones):
        note=(36,38,42,60)[i//10]
        h.append(f'    {{{off},{n},{n-1},{n-1},32768,960,0,0,{note},{note},0}},')
    h+=['};','static const smp_set_t SMP_SETS[]={{"PERC",0,40}};',
        'static const preset_t SMP_PRESET_TABLE[]={{.name="STATTIC",.e={0,0,127,64,110,0,0,0},.env={0,64,100,50}}};']
    target.write_text('\n'.join(h)+'\n')
    print(f'STATTIC drums: 40 shots, 0.5s mono 22050 Hz IMA ADPCM; {len(blob)} bytes; SHA256 {hashlib.sha256(blob).hexdigest()}')

if __name__=='__main__':main()
