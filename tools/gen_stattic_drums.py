"""The forty factory drum shots: the owner's sample set (2026-11-08), assets/stattic-drums/{kk,sd,hh,pr}/,
ten WAV files a category. Each becomes one bounded 22.05 kHz mono IMA ADPCM shot, as the sample manager makes
them: mixed to mono, resampled with a windowed sinc, normalised, at most 1 s, a short fade at its end.
(Before: the forty STATTIC drum presets rendered once, 0.5 s each, by tests/stattic_engine_vectors.c.)
The device only decodes these shots. Pure Python: no extra build dependency.
"""
import hashlib
import math
from pathlib import Path
import re
import sys
from sampleio import ima_encode, read_any_wav

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / 'assets/stattic-drums'
CATEGORIES = ('kk', 'sd', 'hh', 'pr')             # catalog order: shot // 10 is the category
NOTES = (36, 38, 42, 60)
RATE = 22050
MAX_LEN = RATE                                   # 1 s


def natural(p):
    return [int(t) if t.isdigit() else t for t in re.split(r'(\d+)', p.stem)]


def resample(x, sr, to, half=24):
    """windowed-sinc (Blackman) low-pass at the lower Nyquist, evaluated at each output instant"""
    if sr == to:
        return list(x)
    ratio = to / sr
    fc = min(1.0, ratio) * 0.92                 # cut-off, as a fraction of the input Nyquist
    span = int(math.ceil(half / min(1.0, ratio)))
    out, n_out = [], int(len(x) * ratio)
    for k in range(n_out):
        t = k / ratio
        c = int(math.floor(t))
        acc = wsum = 0.0
        for j in range(c - span + 1, c + span + 1):
            if 0 <= j < len(x):
                d = t - j
                arg = math.pi * fc * d
                s = fc if d == 0 else math.sin(arg) / (math.pi * d)
                w = 0.42 + 0.5 * math.cos(math.pi * d / span) + 0.08 * math.cos(2 * math.pi * d / span) if abs(d) < span else 0.0
                acc += x[j] * s * w
                wsum += s * w
        out.append(acc / wsum if wsum else 0.0)
    return out


def shot(path):
    sr, x = read_any_wav(path)
    y = resample(x, sr, RATE)[:MAX_LEN]
    fade = min(110, len(y) // 4)
    for j in range(fade):
        y[-fade + j] *= (fade - 1 - j) / max(1, fade - 1)
    pk = max(1e-9, max(abs(v) for v in y))
    scale = 24000 / pk                          # (read_any_wav gives -1..1: the peak at 24000 of 32767)
    return [max(-32767, min(32767, round(v * scale))) for v in y]


def main():
    target = Path(sys.argv[1])
    blob, zones = bytearray(), []
    for cat, name in enumerate(CATEGORIES):
        files = sorted((SRC / name).glob('*.wav'), key=natural)
        if len(files) != 10:
            raise SystemExit(f'{SRC / name}: {len(files)} WAV files, the catalog needs ten a category')
        for f in files:
            s = shot(f)
            data, _ = ima_encode(s, len(s))
            zones.append((len(blob), len(s), NOTES[cat]))
            blob.extend(data)
    h = ['/* generated by tools/gen_stattic_drums.py; GPL-3.0-only */', '#pragma once',
         '#define SMP_NSETS 1u', '#define SMP_SET_NAMES_INIT "STATTIC"',
         'static const uint8_t SMP_DATA[]={']
    for at in range(0, len(blob), 24):
        h.append('    ' + ','.join(str(x) for x in blob[at:at + 24]) + ',')
    h += ['};', 'static const smp_zone_t SMP_ZONES[]={']
    for off, n, note in zones:
        h.append(f'    {{{off},{n},{n-1},{n-1},32768,960,0,0,{note},{note},0}},')
    h += ['};', 'static const smp_set_t SMP_SETS[]={{"PERC",0,40}};',
          'static const preset_t SMP_PRESET_TABLE[]={{.name="STATTIC",.e={0,0,127,64,110,0,0,0},.env={0,64,100,50}}};']
    target.write_text('\n'.join(h) + '\n')
    print(f'STATTIC drums: 40 shots from {SRC.relative_to(ROOT)}, <=1 s mono 22050 Hz IMA ADPCM; {len(blob)} bytes; '
          f'SHA256 {hashlib.sha256(blob).hexdigest()}')


if __name__ == '__main__':
    main()
